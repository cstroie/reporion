    // Fake HippoBridge resources — the shapes of hippoclient.py's fhir_response()s

    /** @param list<array<string, mixed>> $resources */
    private static function bundle(array $resources): array
    {
        return ['resourceType' => 'Bundle', 'type' => 'searchset', 'total' => \count($resources), 'entry' => array_map(static fn (array $r): array => ['resource' => $r], $resources)];
    }

    private static function scheduled(string $id, string $name, string $modality, string $status, string $when, string $indication = ''): array
    {
        $notes = [['text' => 'MEDICALA']];
        if ($indication !== '') {
            array_unshift($notes, ['text' => $indication, 'category' => [['text' => 'clinical-indication']]]);
        }

        return ['resourceType' => 'ServiceRequest', 'id' => $id, 'status' => $status, 'intent' => 'order', 'identifier' => [['value' => 'R' . $id]],
            'subject' => ['display' => $name], 'category' => [['coding' => [['code' => $modality]]]], 'authoredOn' => $when,
            'requester' => ['display' => 'Dr. Sectie'], 'note' => $notes];
    }

    private static function order(string $id, string $name, string $cnp, string $when, string $procedure, string $region, string $indication, string $requester): array
    {
        return ['resourceType' => 'ServiceRequest', 'id' => $id, 'status' => 'active', 'intent' => 'order',
            'subject' => ['display' => '46 ani', 'identifier' => ['system' => 'http://h/fhir/NamingSystem/patient-cnp', 'value' => $cnp]],
            'extension' => [['url' => 'patientName', 'valueString' => $name]],
            'code' => ['text' => $procedure], 'bodySite' => [['text' => $region]], 'requester' => ['display' => $requester],
            'note' => [['text' => 'MEDICALA'], ['text' => $indication, 'category' => [['text' => 'clinical-indication']]]], 'authoredOn' => $when];
    }

    private static function patientShort(string $id, string $name): array
    {
        return ['resourceType' => 'Patient', 'id' => $id, 'name' => [['use' => 'official', 'text' => $name]], 'gender' => 'female', 'birthDate' => '1980-01-15'];
    }

    private static function patient(string $id, string $family, string $given, string $cnp): array
    {
        return ['resourceType' => 'Patient', 'id' => $id, 'name' => [['use' => 'official', 'family' => $family, 'given' => [$given]]], 'gender' => 'female',
            'identifier' => [['use' => 'official', 'system' => 'http://h/fhir/NamingSystem/patient-cnp', 'value' => $cnp]]];
    }

    /** @param list<string> $regions */
    private static function request(string $id, string $type, string $when, array $regions, string $indication = ''): array
    {
        return ['resourceType' => 'ServiceRequest', 'id' => $id, 'status' => 'active', 'intent' => 'order', 'subject' => ['reference' => 'Patient/p'],
            'code' => ['coding' => [['code' => $type, 'display' => strtoupper($type)]]], 'authoredOn' => $when, 'requester' => ['display' => 'Dr. X'],
            'bodySite' => array_map(static fn (string $r): array => ['text' => $r], $regions)]
            + ($indication !== '' ? ['note' => [['text' => $indication, 'category' => [['text' => 'clinical-indication']]]]] : []);
    }

    /** @param list<array{0: string, 1: string, 2: string, 3: string, 4: string}> $forms */
    private static function report(string $id, string $when, array $forms): array
    {
        return ['resourceType' => 'DiagnosticReport', 'id' => $id, 'status' => 'final', 'effectiveDateTime' => $when,
            'presentedForm' => array_map(static fn (array $f): array => ['contentType' => 'text/markdown', 'title' => $f[0], 'data' => $f[1], 'type' => $f[2], 'region' => $f[3], 'validator' => $f[4]], $forms)];
    }

    /** @param array<string, mixed> $fields */
    private function post(string $user, string $path, array $fields): Response
    {
        return Kernel::boot($this->config)->handle(new Request('POST', $path, cookies: ['reporion' => $this->cookie($user)], body: http_build_query($fields)));
    }

    private function get(string $user, string $path): Response
    {
        [$route, $query] = array_pad(explode('?', $path, 2), 2, '');
        parse_str($query, $params);

        return Kernel::boot($this->config)->handle(new Request('GET', $route, query: array_map('strval', $params), cookies: ['reporion' => $this->cookie($user)]));
    }

    private function cookie(string $user): string
    {
        return (new Session('test-secret', 'reporion', 3600, new FlatFileUserStore($this->dataRoot)))->issue($user);
    }

    private function storage(): FlatFile
    {
        return new FlatFile($this->dataRoot, new Sqlite((string) $this->config['paths']['index'], \dirname(__DIR__, 2) . '/migrations'));
    }
}
