        self::assertSame(422, $this->post('owner', '/admin/plugins/dicom/settings', ['findscu' => 'findscu'] + $bad)->status, 'a full path');
    }

    public function testNamesAndDatesAreReadTheReporionWay(): void
    {
        self::assertSame('IONESCU Maria Elena', Study::name('ionescu^MARIA^ELENA'));
        self::assertSame('POPA Ion', Study::name('POPA^ION=ポパ^イオン'));
