        self::assertFalse(Pacs::sameName('IONESCU Maria', 'IONESCU Mara'));
    }

    // The fake findscu/echoscu

    /**
     * @param list<string> $argv
     *
     * @return array{0: int, 1: string}
     */
    private function fakeFindscu(array $argv, int $timeout): array
    {
        $this->calls[] = $argv;
        $host = $argv[\count($argv) - 2];
        if (isset($this->fail[$host])) {
            return $this->fail[$host];
        }
        if (str_ends_with($argv[0], 'echoscu')) {
            return [0, ''];
        }
        $keys = [];
        $dir = '';
        foreach ($argv as $i => $arg) {
            if ($arg === '-k' && str_contains($argv[$i + 1], '=')) {
                [$k, $v] = explode('=', $argv[$i + 1], 2);
                $keys[$k] = $v;
            }
            if ($arg === '-od') {
                $dir = $argv[$i + 1];
            }
        }
        $n = 0;
        foreach ($this->pacs[$host] ?? [] as $study) {
            if (isset($keys['StudyInstanceUID']) && $keys['StudyInstanceUID'] !== $study['StudyInstanceUID']) {
                continue;
            }
            if (isset($keys['ModalitiesInStudy']) && $keys['ModalitiesInStudy'] !== $study['ModalitiesInStudy']) {
                continue;
            }
            if (isset($keys['StudyDate'])) {
                [$from, $to] = array_pad(explode('-', $keys['StudyDate']), 2, null);
                $to ??= $from;
                if ($study['StudyDate'] < $from || $study['StudyDate'] > $to) {
                    continue;
                }
            }
            $xml = '<?xml version="1.0" encoding="ISO-8859-1"?>' . "\n" . '<data-set xfer="1.2.840.10008.1.2.1" name="Little Endian Explicit">' . "\n";
            foreach ($study as $name => $value) {
                $xml .= '<element tag="0000,0000" vr="LO" vm="1" len="' . \strlen($value) . '" name="' . $name . '">' . htmlspecialchars($value, ENT_XML1, 'ISO-8859-1') . "</element>\n";
            }
            file_put_contents(\sprintf('%s/rsp%04d.xml', $dir, ++$n), $xml . "</data-set>\n");
        }

        return [0, ''];
    }

    /** @return array<string, string> one study, as the PACS stores it (ISO-8859-1 bytes) */
    private static function study(string $uid, string $date, string $time, string $modality, string $name, string $id, string $description, string $accession, string $referrer): array
    {
        return [
            'SpecificCharacterSet' => 'ISO_IR 100', 'StudyDate' => $date, 'StudyTime' => $time, 'AccessionNumber' => $accession,
            'ReferringPhysicianName' => $referrer, 'StudyDescription' => $description, 'PatientName' => $name, 'PatientID' => $id,
            'PatientBirthDate' => '19800115', 'PatientSex' => 'F', 'StudyInstanceUID' => $uid, 'ModalitiesInStudy' => $modality,
        ];
    }

    /** @param array<string, mixed> $fields */
    private function post(string $user, string $path, array $fields): Response
    {
        return Kernel::boot($this->config)->handle(new Request('POST', $path, cookies: ['reporion' => $this->cookie($user)], body: http_build_query($fields)));
    }

    private function get(string $user, string $path): Response
    {
        [$route, $query] = array_pad(explode('?', $path, 2), 2, '');
        parse_str($query, $params);

        return Kernel::boot($this->config)->handle(new Request('GET', $route, query: array_map('strval', $params), cookies: ['reporion' => $this->cookie($user)]));
    }

    private function cookie(string $user): string
    {
        return (new Session('test-secret', 'reporion', 3600, new FlatFileUserStore($this->dataRoot)))->issue($user);
    }

    private function storage(): FlatFile
    {
        return new FlatFile($this->dataRoot, new Sqlite((string) $this->config['paths']['index'], \dirname(__DIR__, 2) . '/migrations'));
    }
