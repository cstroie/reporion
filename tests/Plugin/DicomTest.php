    public function testTheWorklistQueriesEachPacsPerModalityAndMarksReportedStudies(): void
    {
        $this->fail['10.0.1.5'] = [2, "E: Association Request Failed: 0006:031c TCP Initialization Error: Connection refused\n"];
        $this->storage()->create('reports:ct:mioveni:260928-dumitru-elena', ['title' => 'DUMITRU Elena', 'visibility' => 'private', 'study_uid' => self::UID3], "# DUMITRU Elena\n", 'owner');

        $page = $this->get('owner', '/x/dicom/worklist');

        self::assertSame(200, $page->status);
        self::assertCount(3, $this->calls, 'a site with a PACS × 2 modalities, the failing one asked once; the site without our AE title for it never');
        $first = $this->calls[0];
        self::assertSame('/opt/dcmtk/bin/findscu', $first[0]);
        self::assertSame(['-aet', 'RP_MIOVENI'], \array_slice($first, 2, 2), "the site's own calling AE title");
        self::assertSame(['-aet', 'RP_SCUC'], \array_slice($this->calls[2], 2, 2), 'and the other site its own');
        self::assertSame(['-aec', 'MVPACS'], \array_slice($first, 4, 2));
        self::assertSame(['10.0.0.5', '104'], \array_slice($first, -2));
        self::assertContains('StudyDate=20260926-20260929', $first, '3 days back from today');
        self::assertContains('ModalitiesInStudy=CT', $first);
        foreach ($this->calls as $argv) {
            self::assertStringNotContainsString('IONESCU', implode(' ', $argv), 'no name ever on a command line');
            self::assertStringNotContainsString($this->cnp, implode(' ', $argv));
        }
        self::assertStringContainsString('IONESCU Maria', $page->body);
        self::assertStringContainsString('POPÉSCU Ana', $page->body, 'ISO-8859-1 read as UTF-8');
        self::assertStringContainsString('no CNP', $page->body, 'a PACS id that is not a CNP is flagged');
        self::assertStringContainsString('/new?prefill=dicom&amp;ref=' . rawurlencode('mioveni:CT:' . self::UID1), $page->body);
        self::assertStringContainsString('href="/reports:ct:mioveni:260928-dumitru-elena"', $page->body, 'already reported: a link');
        self::assertStringContainsString('The PACS did not answer', $page->body, 'the other site still listed its own error');
        self::assertLessThan(strpos($page->body, 'CT ABDOMEN'), strpos($page->body, 'IRM CEREBRAL'), 'newest first');

        $this->calls = [];
        $one = $this->get('owner', '/x/dicom/worklist?site=mioveni&from=2026-09-28&to=2026-09-28');
        self::assertCount(2, $this->calls);
        self::assertContains('StudyDate=20260928', $this->calls[0]);
        self::assertStringContainsString('IONESCU Maria', $one->body);

        self::assertStringContainsString('at most 31 days', $this->get('owner', '/x/dicom/worklist?from=2026-01-01&to=2026-09-28')->body);
        self::assertSame(404, $this->get('viewer', '/x/dicom/worklist')->status);
    }

    public function testStartingAReportFillsTheGuidedFormFromTheStudy(): void
    {
        $form = $this->get('owner', '/new?prefill=dicom&ref=' . rawurlencode('mioveni:CT:' . self::UID1));

        self::assertSame(200, $form->status);
        self::assertContains('StudyInstanceUID=' . self::UID1, $this->calls[0], 'the one study, by UID');
        foreach (['value="IONESCU Maria"', 'value="' . $this->cnp . '"', 'value="2026-09-28"', 'value="10:15"', 'value="Ct Torace Nativ"', 'POPESCU Ion',
            'name="study_uid" value="' . self::UID1 . '"', 'name="pacs_accession" value="MV26001"'] as $needle) {
            self::assertStringContainsString($needle, $form->body);
        }

        $created = $this->post('owner', '/new', [
            'guided' => '1', 'action' => 'create', 'name' => 'IONESCU Maria', 'cnp' => $this->cnp, 'date' => '2026-09-28', 'time' => '10:15',
            'modality' => 'CT', 'site' => 'mioveni', 'regions' => ['chest'], 'title' => 'Ct Torace Nativ',
            'study_uid' => self::UID1, 'pacs_accession' => 'MV26001',
        ]);
        self::assertSame(302, $created->status);
        $fm = $this->storage()->read(self::REPORT)->frontmatter;
        self::assertSame(self::UID1, $fm['study_uid']);
        self::assertSame('MV26001', $fm['pacs_accession']);
        self::assertStringStartsWith('MV-CT-26-', (string) $fm['accession'], "Reporion's own accession stays (D20)");

        $noCnp = $this->get('owner', '/new?prefill=dicom&ref=' . rawurlencode('mioveni:MR:' . self::UID2));
        self::assertStringContainsString('value="POPÉSCU Ana"', $noCnp->body);
        self::assertStringNotContainsString('PACS00042', $noCnp->body, 'not a CNP: never put in the CNP field');

        self::assertSame(404, $this->get('owner', '/new?prefill=dicom&ref=' . rawurlencode('mioveni:CT:9.9.9'))->status, 'not in the PACS');
        self::assertSame(404, $this->get('owner', '/new?prefill=dicom&ref=' . rawurlencode('nopacs:CT:' . self::UID1))->status, 'a site without a PACS');
        self::assertSame(404, $this->get('owner', '/new?prefill=dicom&ref=mioveni:CT:1.2;rm')->status);
    }

    public function testThePacsTabLinksTheStudyAndFillsOnlyWhatTheReportLacks(): void
    {
        $page = $this->storage()->create(self::REPORT, [
            'title' => 'IONESCU Maria', 'visibility' => 'private', 'modality' => ['CT'], 'site' => 'mioveni',
            'study_date' => '2026-09-28', 'patient' => ['name' => 'Ionescu Maria'], 'referrer' => 'Dr. Deja',
        ], "# IONESCU Maria\n\n## CT torace\n", 'owner');

        $tab = $this->get('owner', '/x/dicom/study/' . $page->pid);
        self::assertSame(200, $tab->status);
        self::assertContains('StudyDate=20260928', $this->calls[0]);
        self::assertContains('ModalitiesInStudy=CT', $this->calls[0], "the report's own modality");
        self::assertCount(1, $this->calls);
        self::assertStringContainsString('same name', $tab->body);
        self::assertLessThan(strpos($tab->body, 'DUMITRU'), strpos($tab->body, 'IONESCU Maria'), 'the likeliest first');
        self::assertStringNotContainsString('IRM CEREBRAL', $tab->body, 'another modality');

        $done = $this->post('owner', '/x/dicom/study/' . $page->pid, ['site' => 'mioveni', 'uid' => self::UID1, 'day' => '2026-09-28']);
        self::assertSame(302, $done->status);
        self::assertStringContainsString('done=1', $done->headers['Location']);
        self::assertStringNotContainsString('ionescu', strtolower($done->headers['Location']));

        $updated = $this->storage()->read(self::REPORT);
        self::assertSame(2, $updated->rev);
        $fm = $updated->frontmatter;
        self::assertSame(['name' => 'Ionescu Maria', 'cnp' => $this->cnp, 'sex' => 'F', 'born' => 1980], $fm['patient'], 'blanks filled, the name kept as written');
        self::assertSame('Dr. Deja', $fm['referrer'], 'never overwritten');
        self::assertStringStartsWith('2026-09-28T10:15:00', (string) $fm['study_date'], 'the time added to the same day');
        self::assertSame('Ct Torace Nativ', $fm['exam_title']);
        self::assertSame(self::UID1, $fm['study_uid']);
        self::assertSame('MV26001', $fm['pacs_accession']);
        self::assertSame($page->body, $updated->body);

        self::assertStringContainsString('done=0', $this->post('owner', '/x/dicom/study/' . $page->pid, ['site' => 'mioveni', 'uid' => self::UID1])->headers['Location']);
        self::assertSame(2, $this->storage()->read(self::REPORT)->rev, 'nothing new: no revision');
        self::assertStringContainsString('>linked<', $this->get('owner', '/x/dicom/study/' . $page->pid)->body);

        $other = $this->post('owner', '/x/dicom/study/' . $page->pid, ['site' => 'mioveni', 'uid' => self::UID3]);
        self::assertSame(422, $other->status);
        self::assertStringContainsString('The CNP in the PACS is not the one on this report', $other->body, 'the CNP check comes first');

        $audit = (string) file_get_contents((string) glob($this->dataRoot . '/audit/*.ndjson')[0]);
        self::assertStringContainsString('"via":"dicom"', $audit);
        self::assertStringNotContainsString('ionescu', strtolower($audit), 'no path or name in the audit (invariant 8)');
    }

